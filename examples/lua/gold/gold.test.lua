-- Run with: mirror test examples/lua/gold   (the map, gold.w3x, is a folder map: a folder holding its war3map.lua)
test("the player is paid every 2 seconds", function()
  local sim = mirror.load("gold.w3x")
  sim:advance(7)
  sim:say(0, "-gold")
  sim:advance(0.1)
  assert_contains(sim:log(), "gold\t30")
end)

test("the same seed gives the same run", function()
  local a, b = mirror.load("gold.w3x", {seed = 3}), mirror.load("gold.w3x", {seed = 3})
  a:advance(30); b:advance(30)
  assert_eq(a:hash(), b:hash())
end)
